// Close-up screenshots of the 3D body: node e2e/body.mjs <base> <outDir>
import { chromium } from 'playwright-core'
const [BASE = 'http://localhost:5199/', OUT = 'e2e/out'] = process.argv.slice(2)
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errs = []
page.on('pageerror', (e) => errs.push(e.message))
await page.goto(BASE + '?e2e', { waitUntil: 'networkidle' })
await page.evaluate(() => localStorage.clear())
await page.goto(BASE + '?e2e', { waitUntil: 'networkidle' })
await page.waitForTimeout(3000)
await page.getByRole('button', { name: 'Load example' }).click()
await page.waitForTimeout(2500)
await page.locator('.stage-canvas').screenshot({ path: `${OUT}/body-full.png` })
console.log('stats', JSON.stringify(await page.evaluate(() => window.__rheum.stats())))
await page.getByRole('button', { name: 'Reset view' }).click()
await page.getByRole('button', { name: 'X-ray' }).click()
await page.waitForTimeout(1500)
await page.locator('.stage-canvas').screenshot({ path: `${OUT}/body-xray.png` })
await page.getByRole('button', { name: 'Back', exact: true }).click()
await page.waitForTimeout(1500)
await page.locator('.stage-canvas').screenshot({ path: `${OUT}/body-xray-back.png` })
console.log('errors', errs.length ? errs : 'none')
await browser.close()
