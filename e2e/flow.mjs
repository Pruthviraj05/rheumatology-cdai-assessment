// End-to-end clinical flow against a running dev/preview server.
// Usage: node e2e/flow.mjs [baseUrl] [screenshotDir]
import { chromium } from 'playwright-core'
import fs from 'node:fs'

const BASE = process.argv[2] ?? 'http://localhost:5199/'
const OUT = process.argv[3] ?? 'e2e/out'
fs.mkdirSync(OUT, { recursive: true })

const browser = await chromium.launch({
  executablePath: process.env.CHROME ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe',
  args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'],
})
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const page = await ctx.newPage()
const problems = []
page.on('pageerror', (e) => problems.push(`pageerror: ${e.message}`))
page.on('console', (m) => {
  if (m.type() === 'error' && !/synchronously unmount a root/.test(m.text())) problems.push(`console.error: ${m.text().slice(0, 200)}`)
})

let passed = 0
let failed = 0
const check = (name, cond, extra = '') => {
  if (cond) {
    passed++
    console.log(`  ✓ ${name}`)
  } else {
    failed++
    console.log(`  ✗ ${name} ${extra}`)
  }
}
const step = (t) => console.log(`\n${t}`)
const txt = async (sel) => (await page.locator(sel).first().innerText()).trim()
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` })
const settle = (ms = 400) => page.waitForTimeout(ms)

await page.goto(BASE + '?e2e', { waitUntil: 'networkidle' })
await page.evaluate(() => localStorage.clear())
await page.goto(BASE + '?e2e', { waitUntil: 'networkidle' })
await page.waitForSelector('canvas')
await settle(2500)

step('1. Initial state')
check('patient shown', (await txt('[data-testid=patient-name]')).includes('DEMO-0001'))
check('status Not started', (await txt('[data-testid=assessment-status]')) === 'Not started')
check('CDAI incomplete, no score shown', (await txt('[data-testid=summary-score]')) === '—')
check('0/28 examined', (await txt('[data-testid=stat-examined]')) === '0/28')
check('Finalize disabled', await page.getByRole('button', { name: /Finalize/ }).isDisabled())
await shot('01-initial')

step('2. 3D: click real markers and record findings')
const click3d = async (id) => {
  const pt = await page.evaluate((i) => window.__rheum.project(i), id)
  await page.mouse.move(pt.x, pt.y)
  await page.mouse.down()
  await page.mouse.up()
  await settle(250)
}
await click3d('wrist_r')
check('Right wrist selected via 3D click', (await txt('[data-testid=selected-joint-name]')) === 'Right wrist')
await page.keyboard.press('t')
await page.keyboard.press('s')
await settle()
check('tender = 1', (await txt('[data-testid=stat-tender]')) === '1')
check('swollen = 1', (await txt('[data-testid=stat-swollen]')) === '1')
await click3d('knee_l')
check('Left knee selected via 3D click', (await txt('[data-testid=selected-joint-name]')) === 'Left knee')
await page.getByRole('button', { name: 'Tender', exact: true }).click()
check('tender = 2 (swelling independent)', (await txt('[data-testid=stat-tender]')) === '2')
check('swollen still 1', (await txt('[data-testid=stat-swollen]')) === '1')
await click3d('ankle_l')
check('Left ankle selected (pain-map joint)', (await txt('[data-testid=selected-joint-name]')) === 'Left ankle')
await page.keyboard.press('t')
await page.keyboard.press('s')
await page.keyboard.press('p')
await settle()
check('ankle does NOT change TJC', (await txt('[data-testid=stat-tender]')) === '2')
check('ankle does NOT change SJC', (await txt('[data-testid=stat-swollen]')) === '1')
check('pain-map badge shown', await page.getByText('Pain map only · not in CDAI').isVisible())
await shot('02-3d-findings')

step('3. Camera controls and region focus')
await page.getByRole('button', { name: 'Back', exact: true }).click()
await settle(900)
await shot('03-back-view')
await page.getByRole('button', { name: 'Right hand', exact: true }).click()
await settle(1400)
check('region focus selected right wrist', (await txt('[data-testid=selected-joint-name]')) === 'Right wrist')
await shot('04-right-hand')
await click3d('mcp2_r')
check('MCP 2 selectable at hand zoom', (await txt('[data-testid=selected-joint-name]')).includes('MCP 2'))
await page.getByRole('button', { name: 'Reset view' }).click()
await settle(1200)

step('4. Bulk normal + guided exam')
await page.getByRole('button', { name: /Mark remaining/ }).click()
await page.getByRole('button', { name: /Record \d+ joints as normal/ }).click()
await settle()
check('28/28 examined', (await txt('[data-testid=stat-examined]')) === '28/28')
check('TJC preserved (2)', (await txt('[data-testid=stat-tender]')) === '2')
check('SJC preserved (1)', (await txt('[data-testid=stat-swollen]')) === '1')
check('still incomplete (globals missing)', (await txt('[data-testid=summary-score]')) === '—')
await page.keyboard.press('Control+z')
await settle()
check('undo restores unexamined joints', (await txt('[data-testid=stat-examined]')) !== '28/28')
await page.getByRole('button', { name: /Mark remaining/ }).click()
await page.getByRole('button', { name: /Record \d+ joints as normal/ }).click()

step('5. Global assessments + live CDAI')
await page.getByRole('tab', { name: 'Score & globals' }).click()
const pt = page.getByRole('group', { name: /Patient global assessment \(PtGA\), whole points/ })
await pt.getByRole('button', { name: '5', exact: true }).click()
check('PtGA 5 -> still incomplete (PrGA missing)', (await txt('[data-testid=summary-score]')) === '—')
const prgaExact = page.locator('fieldset', { hasText: 'Physician global assessment' }).getByPlaceholder('0–10')
await prgaExact.fill('11')
await prgaExact.press('Enter')
check('PrGA 11 rejected', await page.getByText('Value must be between 0 and 10').or(page.getByText(/between 0 and 10/)).first().isVisible())
await prgaExact.fill('3')
await prgaExact.press('Enter')
await settle()
// TJC 2 + SJC 1 + 5 + 3 = 11 -> moderate
check('CDAI = 11', (await txt('[data-testid=summary-score]')) === '11')
check('category Moderate', (await txt('[data-testid=cdai-category]')).includes('Moderate'))
await shot('05-score')
await page.getByRole('button', { name: 'Show calculation breakdown' }).click()
check('breakdown visible', await page.getByText('CDAI = TJC28 + SJC28 + PtGA + PrGA').isVisible())

step('6. Half-point & boundary: remission/low edge via manual counts')
await page.getByRole('button', { name: 'Enter counts manually' }).click()
await page.getByRole('textbox', { name: 'Tender joint count (TJC28)' }).fill('0')
await page.getByRole('textbox', { name: 'Tender joint count (TJC28)' }).press('Enter')
await page.getByRole('textbox', { name: 'Swollen joint count (SJC28)' }).fill('0')
await page.getByRole('textbox', { name: 'Swollen joint count (SJC28)' }).press('Enter')
const ptExact = page.locator('fieldset', { hasText: 'Patient global assessment' }).getByPlaceholder('0–10')
await ptExact.fill('1.1')
await ptExact.press('Enter')
await prgaExact.fill('1.7')
await prgaExact.press('Enter')
await settle()
check('0 + 0 + 1.1 + 1.7 = 2.8 -> Remission', (await txt('[data-testid=summary-score]')) === '2.8' && (await txt('[data-testid=cdai-category]')).includes('Remission'))
await ptExact.fill('1.2')
await ptExact.press('Enter')
await settle()
check('2.9 -> Low', (await txt('[data-testid=summary-score]')) === '2.9' && (await txt('[data-testid=cdai-category]')).includes('Low'))
await page.getByRole('textbox', { name: 'Tender joint count (TJC28)' }).fill('29')
await page.getByRole('textbox', { name: 'Tender joint count (TJC28)' }).press('Enter')
check('TJC 29 rejected', await page.getByText('Enter a whole number from 0 to 28.').isVisible())
await page.getByRole('textbox', { name: 'Tender joint count (TJC28)' }).fill('2')
await page.getByRole('textbox', { name: 'Tender joint count (TJC28)' }).press('Enter')
await page.getByRole('button', { name: 'From joint examination' }).click()
await ptExact.fill('5')
await ptExact.press('Enter')
await prgaExact.fill('3')
await prgaExact.press('Enter')
await settle()
check('back to joint exam: 11', (await txt('[data-testid=summary-score]')) === '11')

step('7. Save draft, reload, reopen')
await page.getByRole('button', { name: 'Save draft' }).click()
await settle(500)
check('draft saved', (await txt('[data-testid=save-state]')).startsWith('Draft saved'))
await page.reload({ waitUntil: 'networkidle' })
await page.waitForSelector('canvas')
await settle(1500)
check('reopened: score 11', (await txt('[data-testid=summary-score]')) === '11')
check('reopened: TJC 2 / SJC 1', (await txt('[data-testid=stat-tender]')) === '2' && (await txt('[data-testid=stat-swollen]')) === '1')

step('8. Review tab + finalize')
await page.getByRole('tab', { name: 'Review' }).click()
check('review lists right wrist as tender', await page.getByRole('button', { name: 'Right wrist' }).first().isVisible())
check('review lists ankle pain', await page.getByRole('button', { name: /Left ankle/ }).first().isVisible())
await shot('06-review')
await page.getByRole('button', { name: 'Finalize…' }).click()
const finalizeBtn = page.getByRole('button', { name: 'Finalize assessment' })
check('finalize needs confirmation', await finalizeBtn.isDisabled())
await page.getByLabel(/I have reviewed these findings/).check()
await finalizeBtn.click()
await settle(600)
check('status Finalized', (await txt('[data-testid=assessment-status]')) === 'Finalized')
check('editing locked', await page.getByRole('button', { name: 'Save draft' }).count() === 0)
await shot('07-finalized')

step('9. Amend with revision history')
await page.getByRole('button', { name: 'Amend…' }).click()
await page.getByRole('tab', { name: 'Score & globals' }).click()
await page.locator('fieldset', { hasText: 'Physician global assessment' }).getByPlaceholder('0–10').fill('4')
await page.locator('fieldset', { hasText: 'Physician global assessment' }).getByPlaceholder('0–10').press('Enter')
await page.getByRole('button', { name: 'Save amendment…' }).click()
check('amend requires reason', await page.getByRole('button', { name: 'Save amendment', exact: true }).isDisabled())
await page.getByPlaceholder(/Physician global re-scored/).fill('Physician global re-scored after review')
await page.getByLabel(/I have reviewed these findings/).check()
await page.getByRole('button', { name: 'Save amendment', exact: true }).click()
await settle(600)
check('amended score 12', (await txt('[data-testid=summary-score]')) === '12')
await page.getByRole('tab', { name: 'Review' }).click()
check('revision history lists original', await page.getByText('Revision 2', { exact: true }).first().isVisible())
check('amendment reason shown', await page.getByText(/Physician global re-scored after review/).first().isVisible())

step('10. New visit shows history, no fabricated data')
await page.getByRole('button', { name: '+ New visit' }).click()
await settle(500)
check('new visit starts empty', (await txt('[data-testid=assessment-status]')) === 'Not started')
await page.getByRole('tab', { name: 'Review' }).click()
check('history shows previous assessment', await page.locator('table.history tbody tr').count() === 1)

step('11. 2D chart supports the same workflow')
await page.getByRole('button', { name: '2D chart' }).click()
await settle(500)
await page.locator('g.marker2d[data-joint-id=mcp2_r]').click()
await page.getByRole('tab', { name: 'Joint exam' }).click()
check('2D click selects joint', (await txt('[data-testid=selected-joint-name]')).includes('MCP 2'))
await page.getByRole('button', { name: 'Tender', exact: true }).click()
await page.getByRole('button', { name: 'Swollen', exact: true }).click()
check('2D: TJC 1', (await txt('[data-testid=stat-tender]')) === '1')
check('2D: SJC 1', (await txt('[data-testid=stat-swollen]')) === '1')
await shot('08-2d-chart')

step('12. Read-only role')
await page.getByLabel('Role').selectOption('viewer')
await settle(500)
check('view-only banner', await page.getByText('view-only access').isVisible())
check('save disabled', await page.getByRole('button', { name: 'Save draft' }).isDisabled())

step('13. Responsive')
for (const [w, h, n] of [[1024, 768, 'tablet'], [390, 844, 'phone']]) {
  await page.setViewportSize({ width: w, height: h })
  await settle(900)
  await shot(`09-${n}`)
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2)
  check(`${n}: no horizontal page scroll`, !overflow)
}

step('Console / runtime errors')
check('no page errors', problems.length === 0, problems.join(' | '))

console.log(`\n${passed} passed, ${failed} failed`)
await browser.close()
process.exit(failed ? 1 : 0)
