// Regenerates README screenshots: node e2e/screens.mjs [baseUrl]
import { chromium } from 'playwright-core'
const BASE = process.argv[2] ?? 'http://localhost:4199/'
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto(BASE + '?e2e', { waitUntil: 'networkidle' })
await page.evaluate(() => localStorage.clear())
await page.goto(BASE + '?e2e', { waitUntil: 'networkidle' })
await page.waitForSelector('canvas')
await page.waitForTimeout(2500)
await page.getByRole('button', { name: 'Start' }).click()
await page.waitForTimeout(1800)
await page.screenshot({ path: 'docs/screenshots/1-joints.png' })
await page.getByRole('button', { name: 'Load example' }).click()
await page.waitForTimeout(2000)
await page.getByRole('button', { name: 'Dismiss message' }).click()
await page.getByRole('navigation', { name: 'Steps' }).getByRole('button').nth(2).click()
await page.waitForTimeout(800)
await page.screenshot({ path: 'docs/screenshots/3-result.png' })
await page.getByRole('navigation', { name: 'Steps' }).getByRole('button').nth(1).click()
await page.getByRole('button', { name: 'X-ray' }).click()
await page.waitForTimeout(1500)
await page.screenshot({ path: 'docs/screenshots/2-rating-xray.png' })
await page.setViewportSize({ width: 390, height: 844 })
await page.getByRole('button', { name: 'X-ray' }).click()
await page.getByRole('navigation', { name: 'Steps' }).getByRole('button').nth(2).click()
await page.waitForTimeout(1500)
await page.screenshot({ path: 'docs/screenshots/phone.png' })
await browser.close()
