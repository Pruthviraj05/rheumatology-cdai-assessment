// Regenerates README screenshots: node e2e/screens.mjs [baseUrl]
import { chromium } from 'playwright-core'
const BASE = process.argv[2] ?? 'http://localhost:4199/'
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto(BASE, { waitUntil: 'networkidle' })
await page.evaluate(() => localStorage.clear())
await page.goto(BASE, { waitUntil: 'networkidle' })
await page.waitForSelector('canvas')
await page.getByRole('button', { name: 'Load demo findings' }).click()
await page.waitForTimeout(2500)
await page.getByRole('button', { name: 'Dismiss message' }).click()
await page.getByRole('tab', { name: 'Score & globals' }).click()
await page.waitForTimeout(600)
await page.screenshot({ path: 'docs/screenshots/05-score.png' })
await page.getByRole('tab', { name: 'Joint exam' }).click()
await page.locator('.joint-row[data-joint-id=wrist_r]').click()
await page.getByRole('button', { name: 'Right hand', exact: true }).click()
await page.waitForTimeout(1800)
await page.screenshot({ path: 'docs/screenshots/hand-3d.png' })
await page.getByRole('button', { name: '2D chart' }).click()
await page.waitForTimeout(600)
await page.screenshot({ path: 'docs/screenshots/2d-chart.png' })
await browser.close()
